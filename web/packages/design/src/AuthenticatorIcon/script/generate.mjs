// build.assets/generate-aaguids.sh resolves the dataset's commit and passes it down. A hand run has
// nothing to pin against, so it says so rather than claiming a revision it did not read.
//
// Both halves describe the input, never the run: stamping the time of generation would make every
// regeneration a diff, and when the files were last regenerated is already in their git history.
const sourceCommit = process.env.AAGUID_SOURCE_COMMIT || 'unknown revision';
const sourceDate = process.env.AAGUID_SOURCE_DATE || 'unknown date';

const GENERATED =
  `// THIS FILE IS GENERATED by script/generate.mjs. DO NOT EDIT.\n` +
  `// Generated from passkey-authenticator-aaguids@${sourceCommit}, committed ${sourceDate}.\n`;

// Names double as the default device nickname in the web UI and tsh, so they are clipped to the
// server's defaults.MFADeviceNameMaxLen (lib/defaults/defaults.go). That limit counts bytes, not
// characters. This script cannot import the app's copy of it (MAX_DEVICE_NAME_BYTES in
// teleport/services/mfa/passkeyName.ts), so deviceNameLimit.test.ts fails if the two drift apart.
const MAX_NAME_BYTES = 30;

// Vendor names in the dataset are marketing strings: long, parenthesized, and suffixed with edition
// or preview qualifiers and MDS product codes. We surface a short human label instead.
function normalizeName(raw) {
  const n = raw
    .replace(/\s*\([^)]*\)/g, '') // drop parentheticals e.g. "(Enterprise Profile)"
    .replace(/\s+-\s+.*\bEdition\b.*$/i, '') // drop "- ... Edition ..." tails
    .replace(/\s+(?:RC\s+)?Preview$/i, '') // drop trailing "Preview" / "RC Preview"
    .replace(/\s+\d[A-Z0-9]{3,}(?:-\d+)?$/, '') // drop trailing MDS codes e.g. "1VDJSN-2"
    .replace(/\s+/g, ' ')
    .trim();

  let out = '';
  for (const char of n) {
    if (Buffer.byteLength(out + char, 'utf8') > MAX_NAME_BYTES) {
      break;
    }

    out += char;
  }

  return out.trim();
}

function slug(name) {
  return name
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
}

function identBase(name) {
  let b = name.replace(/[^a-zA-Z0-9]/g, '') || 'auth';

  // A JS identifier cannot start with a digit, and many device names do (e.g. "1Password").
  if (/^[0-9]/.test(b)) {
    return `_${b}`;
  }

  return b;
}

function decode(uri) {
  const m = /^data:([^;,]+);base64,(.*)$/s.exec(uri || '');
  if (!m) {
    return null;
  }

  const ext = EXT[m[1]];
  if (!ext) {
    return null;
  }

  return { ext, buf: Buffer.from(m[2], 'base64') };
}

// build.assets/generate-aaguids.sh passes the dataset it fetched; fetch it directly when run by hand.
const src = process.argv[2];
const raw = src
  ? JSON.parse(readFileSync(src, 'utf8'))
  : await (await fetch(UPSTREAM_URL)).json();

rmSync(assetsDir, { recursive: true, force: true });
mkdirSync(assetsDir, { recursive: true });

const importLines = [];
const iconEntries = [];
// AAGUID -> vendor name. Emitted as JSON so the Go server can embed the same table the web UI uses.
const names = {};

// Assets are content-addressed: identical bytes are written once and shared by every AAGUID that
// resolves to them. The dataset repeats a handful of vendor marks across dozens of records (all 160
// Yubico files are two distinct images), so this keeps assets/ proportional to the number of distinct
// marks. Pinning the export name to the digest also turns a vendor changing artwork into a visible
// rename at review time rather than a silent asset swap.
const byContent = new Map();

function emitAsset(fileBase, identName, ext, buf) {
  const digest = createHash('sha256').update(buf).digest('hex').slice(0, 8);
  const key = `${digest}.${ext}`;

  const cached = byContent.get(key);
  if (cached) {
    return cached;
  }

  const file = `${fileBase}-${digest}.${ext}`;
  const ident = `${identName}_${digest}`;

  writeFileSync(join(assetsDir, file), buf);

  importLines.push(
    `export { default as ${ident} } from './assets/${file}?no-inline';`
  );
  byContent.set(key, ident);

  return ident;
}

// Overrides are emitted ahead of the dataset so that a dataset icon carrying identical bytes dedups onto the override's
// export rather than the other way round.
const overrideIcons = new Map();
const overrideHits = new Map();

for (const o of iconOverrides) {
  if (overrideIcons.has(o.id)) {
    throw new Error(`duplicate icon override id ${o.id}`);
  }

  const variants = {};
  for (const variant of ['light', 'dark']) {
    const rel = o[variant] ?? o.icon;
    if (!rel) {
      continue;
    }

    const src = join(overridesDir, rel);
    if (!existsSync(src)) {
      throw new Error(`icon override ${o.id}: ${src} does not exist`);
    }

    const ext = rel.split('.').pop().toLowerCase();
    if (!Object.values(EXT).includes(ext)) {
      throw new Error(`icon override ${o.id}: unsupported asset type .${ext}`);
    }

    variants[variant] = emitAsset(
      `override-${slug(o.id)}`,
      `override_${identBase(o.id)}`,
      ext,
      readFileSync(src)
    );
  }

  if (!variants.light && !variants.dark) {
    throw new Error(
      `icon override ${o.id}: no icon, light or dark asset given`
    );
  }

  overrideIcons.set(o.id, variants);
}

// Sorted so that neither asset filenames nor export names depend on the dataset's key order: the first record to claim
// a shared image is the one that names it.
const entries = Object.entries(raw).toSorted(([a], [b]) => a.localeCompare(b));

for (const [aaguid, entry] of entries) {
  const name = normalizeName(entry.name || '');
  const override = iconOverrides.find(o => o.match.test(entry.name || ''));

  let variants = {};
  if (override) {
    overrideHits.set(override.id, (overrideHits.get(override.id) || 0) + 1);
    variants = overrideIcons.get(override.id);
  } else {
    for (const [variant, key] of [
      ['light', 'icon_light'],
      ['dark', 'icon_dark'],
    ]) {
      const d = decode(entry[key]);
      if (!d) {
        continue;
      }

      variants[variant] = emitAsset(
        slug(name) || aaguid.slice(0, 8),
        identBase(name),
        d.ext,
        d.buf
      );
    }
  }

  const light = variants.light || variants.dark;
  const dark = variants.dark || variants.light;

  names[aaguid] = name;

  if (light || dark) {
    iconEntries.push(
      `  '${aaguid}': {${light ? ` light: i.${light},` : ''}${dark ? ` dark: i.${dark},` : ''} },`
    );
  }
}

const stale = iconOverrides.filter(o => !overrideHits.has(o.id));
if (stale.length) {
  throw new Error(
    `icon override(s) matched no authenticator: ${stale.map(o => o.id).join(', ')}`
  );
}

const iconsPath = join(root, 'icons.ts');
const specsPath = join(root, 'authenticatorIcons.ts');

writeFileSync(
  iconsPath,
  LICENSE + '\n' + GENERATED + importLines.sort().join('\n') + '\n'
);

writeFileSync(
  specsPath,
  LICENSE +
    '\n' +
    GENERATED +
    `import * as i from './icons';\n\n` +
    `export type AuthenticatorIcons = { light?: string; dark?: string };\n\n` +
    `export const authenticatorIcons: Record<string, AuthenticatorIcons> = {\n` +
    iconEntries.sort().join('\n') +
    `\n};\n`
);

// Sorted keys and a single line: the table is data, not source, and a stable key order keeps
// regeneration diffs to the entries that actually changed.
const sortedNames = Object.fromEntries(
  Object.entries(names).toSorted(([a], [b]) => a.localeCompare(b))
);
writeFileSync(namesPath, `${JSON.stringify(sortedNames)}\n`);

console.log(
  `generated ${Object.keys(names).length} names, ${iconEntries.length} icon entries, ${byContent.size} assets`
);

for (const [id, n] of overrideHits) {
  console.log(`icon override ${id}: ${n} specs`);
}
