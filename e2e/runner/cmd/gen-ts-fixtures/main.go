package main

import (
	"bytes"
	"fmt"
	"os"
	"path/filepath"

	template "github.com/DataDog/datadog-agent/pkg/template/text"

	"github.com/gravitational/teleport/e2e/runner/fixtures"
)

var tmpl = template.Must(template.New("fixtures.ts").Parse(`// Code generated by e2e/runner/cmd/gen-ts-fixtures; DO NOT EDIT.

import { test as base } from '@playwright/test';

export type Fixture =
{{- range .Fixtures}}
  | '{{.Name}}'
{{- end}};

export const test = base.extend<{ fixtures: Fixture[] }>({
  fixtures: [[], { option: true }],
});
`))

func main() {
	all := fixtures.All()
	if len(all) == 0 {
		fmt.Fprintln(os.Stderr, "no fixtures registered")
		os.Exit(1)
	}

	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, struct{ Fixtures []*fixtures.Fixture }{all}); err != nil {
		fmt.Fprintf(os.Stderr, "executing template: %v\n", err)
		os.Exit(1)
	}

	outPath := filepath.Join("..", "helpers", "fixtures.ts")
	if err := os.WriteFile(outPath, buf.Bytes(), 0644); err != nil {
		fmt.Fprintf(os.Stderr, "writing %s: %v\n", outPath, err)
		os.Exit(1)
	}

	fmt.Printf("generated %s with %d fixture(s)\n", outPath, len(all))
}
