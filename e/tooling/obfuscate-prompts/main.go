// A tool that obfuscates LLM prompts to make it harder to extract them from
// the binary. We do it to make it more difficult to exploit their weaknesses.

package main

import (
	"fmt"
	"os"
	"path/filepath"
	"time"

	"github.com/gravitational/teleport/e/lib/auth/summarizer/prompts"
)

const (
	dir          = "lib/auth/summarizer/prompts"
	codeTemplate = `// Code generated by "make obfuscate-prompts". DO NOT EDIT.

package prompts

// A random number generator seed for reading obfuscated prompts
const promptSeed uint64 = %d
`
)

func main() {
	stems := []string{"prompt-db", "prompt-ssh"}
	seed := uint64(time.Now().Unix())

	for _, stem := range stems {
		inPath := filepath.Join(dir, stem+".txt")
		text, err := os.ReadFile(inPath)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Could not read file %s: %s\n", inPath, err)
			os.Exit(1)
		}

		obfuscated := prompts.Obfuscate(seed, text)

		outPath := filepath.Join(dir, stem+".bin")
		err = os.WriteFile(outPath, obfuscated, 0666)
		if err != nil {
			fmt.Fprintf(os.Stderr, "Could not write file %s: %s\n", outPath, err)
			os.Exit(1)
		}
	}

	seedSourceCode := fmt.Sprintf(codeTemplate, seed)
	seedPath := filepath.Join(dir, "seed.go")
	err := os.WriteFile(seedPath, []byte(seedSourceCode), 0666)
	if err != nil {
		fmt.Fprintf(os.Stderr, "Could not write file %s: %s\n", seedPath, err)
		os.Exit(1)
	}
}
