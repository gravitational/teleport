func TestGetCrownJewel(t *testing.T) {
	t.Parallel()

	s := newWebSuite(t)
	authClient := s.newAdminAuthClient(s.ctx, t)

	ctx := context.Background()
	createCrownJewel(t, ctx, authClient, 0)

	webPack := s.newAuthWebPack(t, "foo")
	getEndpoint := webPack.clt.Endpoint("enterprise", "crownjewels", "test-0")
	resp, err := webPack.clt.Get(ctx, getEndpoint, nil)
	require.NoError(t, err)

	require.Equal(t, http.StatusOK, resp.Code())

	// Read the response
	var cj ui.CrownJewel
	err = json.Unmarshal(resp.Bytes(), &cj)
	require.NoError(t, err)

	require.Equal(t, "test-0", cj.Name)
	require.Len(t, cj.Spec.TeleportMatchers, 1)
	require.Equal(t, "SELECT * FROM nodes", cj.Spec.Query)
	require.Equal(t, ui.TeleportMatcher{
		Kinds:  []string{"node"},
		Names:  []string{"test"},
		Labels: map[string][]string{},
	}, cj.Spec.TeleportMatchers[0])
}

func TestCreateCrownJewel(t *testing.T) {
	t.Parallel()

	s := newWebSuite(t,
		// Disable retry interval to prevent test from hanging
		// because it uses the fake clock.
		withRunWhileLockedRetryInterval(-1*time.Millisecond),
	)
	webPack := s.newAuthWebPack(t, "foo")
	authClient := s.newAdminAuthClient(s.ctx, t)

	ctx := context.Background()
	generateEndpoint := webPack.clt.Endpoint("enterprise", "crownjewels")
	resp, err := webPack.clt.PostJSON(ctx, generateEndpoint, createCrownJewelRequest{
		Query:       "SELECT * FROM nodes",
		Description: "test description",
		TeleportMatcher: crownjewelv1.TeleportMatcher_builder{
			Kinds: []string{"node"},
			Names: []string{"test"},
		}.Build(),
	})
	require.NoError(t, err)

	require.Equal(t, http.StatusOK, resp.Code())

	// Read the response
	var cj ui.CrownJewel
	err = json.Unmarshal(resp.Bytes(), &cj)
	require.NoError(t, err)
	// The name is generated by the server, and it should not be empty.
	require.NotEmpty(t, cj.Name)

	require.Len(t, cj.Spec.TeleportMatchers, 1)
	require.Equal(t, ui.TeleportMatcher{
		Kinds:  []string{"node"},
		Names:  []string{"test"},
		Labels: map[string][]string{},
	}, cj.Spec.TeleportMatchers[0])
	require.Equal(t, "SELECT * FROM nodes", cj.Spec.Query)
	require.Equal(t, "test description", cj.Description)

	authResp, _, err := authClient.CrownJewelServiceClient().ListCrownJewels(ctx, 0 /* default limit */, "")
	require.NoError(t, err)

	require.Len(t, authResp, 1)
	require.Equal(t, "test", authResp[0].GetSpec().GetTeleportMatchers()[0].GetNames()[0])
}

