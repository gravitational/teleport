// oktaSettings holds externally-supplied, high-level options and to the Okta
// service factory (As opposed to the okta.Config struct, which holds a lot of
// implementation details)
type oktaSettings struct {
	apiEndPoint           string
	pluginStatusSink      common.StatusSink
	syncPeriod            time.Duration
	userSyncEnabled       bool
	ssoConnectorID        string
	accessListSyncEnabled bool
	defaultOwners         []string
	appFilters            []string
	groupFilters          []string
	oktaAppID             string
	appGroupSyncDisabled  bool
	scimEnabled           bool
	oktaAuthProvider      api.AuthProvider
}

func (s *oktaSettings) orgURLBase64() string {
	orgURL := strings.TrimSuffix(s.apiEndPoint, "/")
	return base64.RawURLEncoding.EncodeToString([]byte(orgURL))
}

// InitOkta will initialize and start the Okta service.
func InitOkta(process *service.TeleportProcess) error {
	tokenBytes, err := os.ReadFile(process.Config.Okta.APITokenPath)
	if err != nil {
		return trace.Wrap(err)
	}

	// Remove any leading and trailing whitespace from the token.
	token := strings.TrimSpace(string(tokenBytes))

	process.RegisterWithAuthServer(types.RoleOkta, OktaIdentityEvent)
	process.RegisterCriticalFunc(oktaInit, func() error {
		return initOktaService(process.ExitContext(), process,
			oktaSettings{
				apiEndPoint:           process.Config.Okta.APIEndpoint,
				syncPeriod:            process.Config.Okta.SyncSettings.AppGroupSyncPeriod,
				userSyncEnabled:       false,
				accessListSyncEnabled: process.Config.Okta.SyncSettings.SyncAccessLists,
				defaultOwners:         process.Config.Okta.SyncSettings.DefaultOwners,
				appFilters:            process.Config.Okta.SyncSettings.AppFilters,
				groupFilters:          process.Config.Okta.SyncSettings.GroupFilters,
				oktaAuthProvider:      api.NewSSWSAuthProvider(token),
			},
			process.GetID())
	})
	return nil
}

// OktaPluginPrams holds the parameters needed to initialize the Okta plugin.
type OktaPluginPrams struct {
	// Process is the Teleport process.
	Process *service.TeleportProcess
	// PluginStatusSink is the sink for plugin status events.
	PluginStatusSink common.StatusSink
	// Settings are the Okta settings.
	Settings types.PluginOktaSettings
	// Token is the Okta API token.
	Token string
	// PluginName is the name of the plugin.
	PluginName string
	// AppGroupSyncDisabled allows to disable app group sync.
	AppGroupSyncDisabled bool
	// SCIMEnabled indicates that SCIM sync is enabled for this plugin
	// instance.
	SCIMEnabled bool
	// AuthProvider is the Okta auth provider.
	AuthProvider api.AuthProvider
}

// InitOktaPlugin will initialize and start the Okta service for plugin use. This will not
// fail the parent process on failure. A close event will be emitted when the okta init function ends.
func InitOktaPlugin(ctx context.Context, params OktaPluginPrams) string {
	// timestamp will be used to have a unique value to append to the end of the events generated by the Okta service.
	timestamp := fmt.Sprintf("%d", params.Process.Clock.Now().Unix())

	components := []string{params.PluginName, timestamp}
	identityEvent := EventWithComponents(OktaIdentityEvent, components...)

	process := params.Process
	settings := params.Settings
	// Set the expected instance role for this identity event since it's unique to this plugin.
	process.SetExpectedHostedPluginRole(types.RoleOkta, identityEvent)

	process.RegisterWithAuthServer(types.RoleOkta, identityEvent)
	process.RegisterFunc(oktaInit, func() error {
		return initOktaService(ctx, process,
			oktaSettings{
				userSyncEnabled:       settings.SyncSettings.SyncUsers,
				appGroupSyncDisabled:  params.AppGroupSyncDisabled,
				accessListSyncEnabled: settings.SyncSettings.SyncAccessLists,
				apiEndPoint:           settings.OrgUrl,
				pluginStatusSink:      params.PluginStatusSink,
				ssoConnectorID:        settings.SyncSettings.SsoConnectorId,
				defaultOwners:         settings.SyncSettings.DefaultOwners,
				appFilters:            settings.SyncSettings.AppFilters,
				groupFilters:          settings.SyncSettings.GroupFilters,
				oktaAppID:             settings.SyncSettings.AppId,
				scimEnabled:           params.SCIMEnabled,
				oktaAuthProvider:      params.AuthProvider,
			},
			pluginLogComponent(params.PluginName), components...)
	})

	return EventWithComponents(OktaStopped, components...)
}

// initOktaService initializes, starts, and waits for the Okta service.
func initOktaService(ctx context.Context, process *service.TeleportProcess, settings oktaSettings, logComponent string, components ...string) error {
	defer process.BroadcastEvent(service.Event{Name: EventWithComponents(OktaStopped, components...), Payload: nil})

	logger := process.Config.Logger.With(teleport.ComponentKey, teleport.Component(eteleport.ComponentOkta, logComponent))

	conn, err := process.WaitForConnector(EventWithComponents(OktaIdentityEvent, components...), logger)
	if conn == nil {
		return trace.Wrap(err)
	}

	accessPoint, cacheCleanup, err := newLocalCacheForOkta(process, conn.Client, []string{eteleport.ComponentOkta})
	if err != nil {
		return trace.Wrap(err)
	}

	// Cleanup the cache if a cleanup function is returned.
	if cacheCleanup != nil {
		defer func() {
			if err := cacheCleanup(); err != nil {
				logger.WarnContext(process.ExitContext(), "Error while closing Okta cache", "error", err)
			}
		}()
	}

	// Create the authorizer.
	clusterName := conn.ClusterName()
	lockWatcher, err := services.NewLockWatcher(ctx, services.LockWatcherConfig{
		ResourceWatcherConfig: services.ResourceWatcherConfig{
			Component: eteleport.ComponentOkta,
			Logger:    process.Config.Logger.With(teleport.ComponentKey, teleport.Component(eteleport.ComponentOkta, logComponent)),
			Client:    conn.Client,
		},
	})
	if err != nil {
		return trace.Wrap(err)
	}

	authorizer, err := authz.NewAuthorizer(authz.AuthorizerOpts{
		ClusterName: clusterName,
		AccessPoint: accessPoint,
		LockWatcher: lockWatcher,
	})
	if err != nil {
		return trace.Wrap(err)
	}

	// asyncEmitter makes sure that sessions do not block
	// in case if connections are slow
	asyncEmitter, err := process.NewAsyncEmitter(conn.Client)
	if err != nil {
		return trace.Wrap(err)
	}

	// Make sure that we close the emitter when this function exits
	defer func() {
		if err := asyncEmitter.Close(); err != nil {
			logger.WarnContext(process.ExitContext(), "Error while closing emitter", "error", err)
		}
	}()

	tlsConfig, err := conn.ServerTLSConfig(process.Config.CipherSuites)
	if err != nil {
		return trace.Wrap(err)
	}

	oktaLeader, err := leader.New(leader.Config{
		SemaphoreKind: okta.OktaServiceSemaphoreKind,
		SemaphoreName: settings.orgURLBase64(),
		HostIDHolder:  process.Config.HostUUID,
		Clock:         process.Clock,
		Semaphores:    accessPoint,
	})
	if err != nil {
		return trace.Wrap(err)
	}
	oktaLeader.Start(ctx)

	oktaService, err := okta.New(ctx, okta.Config{
		Leader:                     oktaLeader,
		ConnectorService:           conn.Client,
		Logger:                     process.Config.Logger.With(teleport.ComponentKey, teleport.Component(eteleport.ComponentOkta, logComponent)),
		Clock:                      process.Clock,
		TLSConfig:                  tlsConfig,
		Authorizer:                 authorizer,
		ClusterName:                clusterName,
		Hostname:                   process.Config.Hostname,
		HostID:                     process.Config.HostUUID,
		RotationGetter:             process.GetRotation,
		Emitter:                    asyncEmitter,
		AccessPoint:                accessPoint,
		Access:                     conn.Client,
		AccessLists:                conn.Client.AccessListClient(),
		OnHeartbeat:                process.OnHeartbeat(teleport.Okta),
		OktaAPIEndpoint:            settings.apiEndPoint,
		PluginStatusSink:           settings.pluginStatusSink,
		TimeBetweenSyncs:           settings.syncPeriod,
		UserSyncEnabled:            settings.userSyncEnabled,
		DisableAppGroupSync:        settings.appGroupSyncDisabled,
		SSOConnectorID:             settings.ssoConnectorID,
		AccessListSyncEnabled:      settings.accessListSyncEnabled,
		DefaultOwners:              settings.defaultOwners,
		AccessListSyncAppFilters:   settings.appFilters,
		AccessListSyncGroupFilters: settings.groupFilters,
		OktaSAMLAppID:              settings.oktaAppID,
		SCIMEnabled:                settings.scimEnabled,
		AuthProvider:               settings.oktaAuthProvider,
	})
	if err != nil {
		return trace.Wrap(err)
	}

	var oktaServiceMu sync.Mutex

	process.OnExit("okta.stop", func(payload interface{}) {
		if err := conn.Close(); err != nil {
			logger.WarnContext(ctx, "Error while closing connection", "error", err)
		}
		logger.InfoContext(process.ExitContext(), "Shutting down.")
		if err := oktaLeader.Close(); err != nil {
			logger.WarnContext(process.ExitContext(), "Error closing Okta leader", "error", err)
		}
		var ctx context.Context
		if payload != nil {
			payloadCtx, ok := payload.(context.Context)
			if ok {
				ctx = payloadCtx
			}
		}

		oktaServiceMu.Lock()
		defer oktaServiceMu.Unlock()
		closeOktaService(ctx, logger, oktaService)
	})

	process.BroadcastEvent(service.Event{Name: EventWithComponents(OktaReady, components...), Payload: nil})

	if err := oktaService.Start(ctx); err != nil {
		return trace.Wrap(err)
	}

	logger.InfoContext(process.ExitContext(), "Okta service has successfully started")

	oktaService.Wait(ctx)

	// If we get here, we can attempt to clean up the service. Either this is a result of the
	// context being canceled (will happen with plugins), or the OnExit is running.
	// If OnExit has finished, the Okta service's Shutdown/Close will be skipped.
	oktaServiceMu.Lock()

	// We'll use a context with a short timeout in case Close() was not run by OnExit.
	closeCtx, cancel := context.WithTimeout(context.Background(), 5*time.Second)
	closeOktaService(closeCtx, logger, oktaService)
	cancel()

	// Set the okta service to nil so that the OnExit function is not holding onto a reference
	// to the okta service despite no longer being necessary.
	oktaService = nil
	oktaServiceMu.Unlock()

	return nil
}

// combinedOktaClient is an auth.Client client with services.Okta added to it.
type combinedOktaClient struct {
	authclient.ClientI
	services.AccessLists
	services.Okta
}

// newLocalCacheForOkta returns a new instance of access point for an Okta service. Returns
// a cleanup function for the cache as well.
func newLocalCacheForOkta(process *service.TeleportProcess, clt authclient.ClientI, cacheName []string) (authclient.OktaAccessPoint, func() error, error) {
	accessListClient := clt.AccessListClient()
	oktaClient := clt.OktaClient()
	client := combinedOktaClient{clt, accessListClient, oktaClient}
	// if caching is disabled, return access point
	if !process.Config.CachePolicy.Enabled {
		return client, nil, nil
	}
	cache, err := process.NewLocalCache(clt, cache.ForOkta, cacheName)
	if err != nil {
		return nil, nil, trace.Wrap(err)
	}
	return authclient.NewOktaWrapper(client, cache), cache.Close, nil
}

// closeOktaService will close the Okta service.
func closeOktaService(ctx context.Context, log *slog.Logger, oktaService *okta.Service) {
	// Don't bother if the Okta service is nil.
	if oktaService == nil {
		return
	}

	if err := oktaService.Shutdown(); err != nil {
		log.ErrorContext(ctx, "Error shutting down Okta service", "error", err)
	}

	if ctx != nil {
		if err := oktaService.Close(ctx); err != nil {
			log.ErrorContext(ctx, "Error closing Okta service", "error", err)
		}
	}
}
