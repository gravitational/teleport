// ValidateSAMLResponse consumes attribute statements from SAML identity provider
func (sas *SAMLAuthService) ValidateSAMLResponse(ctx context.Context, samlResponse, connectorID, clientIP string) (*authclient.SAMLAuthResponse, error) {
	if sas.licenseChecker.IsDisabled() {
		return nil, ErrLicenseExpired
	}

	event := &apievents.UserLogin{
		Metadata: apievents.Metadata{
			Type: events.UserLoginEvent,
		},
		Method:      events.LoginMethodSAML,
		ConnectorID: connectorID,
	}

	diagCtx := auth.NewSSODiagContext(types.KindSAML, sas.auth)

	auth, loginIP, err := sas.validateSAMLResponse(ctx, diagCtx, samlResponse, connectorID, clientIP)
	diagCtx.Info.Error = trace.UserMessage(err)

	diagCtx.WriteToBackend(ctx)

	event.AppliedLoginRules = diagCtx.Info.AppliedLoginRules
	event.ConnectionMetadata = apievents.ConnectionMetadata{
		RemoteAddr: loginIP,
	}

	attributeStatements := diagCtx.Info.SAMLAttributeStatements
	if attributeStatements != nil {
		attributes, err := apievents.EncodeMapStrings(attributeStatements)
		if err != nil {
			event.Status.UserMessage = fmt.Sprintf("Failed to encode identity attributes: %v", err.Error())
			logger.DebugContext(ctx, "Failed to encode identity attributes", "error", err)
		} else {
			event.IdentityAttributes = attributes
		}
	}

	if err != nil {
		event.Code = events.UserSSOLoginFailureCode
		if diagCtx.Info.TestFlow {
			event.Code = events.UserSSOTestFlowLoginFailureCode
		}
		event.Status.Success = false
		event.Status.Error = trace.Unwrap(err).Error()
		event.Status.UserMessage = err.Error()
		if err := sas.emitter.EmitAuditEvent(ctx, event); err != nil {
			logger.WarnContext(ctx, "Failed to emit SAML login failed event", "error", err)
		}
		return nil, trace.Wrap(err)
	}

	event.Status.Success = true
	event.User = auth.Username
	event.Code = events.UserSSOLoginCode
	if diagCtx.Info.TestFlow {
		event.Code = events.UserSSOTestFlowLoginCode
	}

	if err := sas.emitter.EmitAuditEvent(ctx, event); err != nil {
		logger.WarnContext(ctx, "Failed to emit SAML login event", "error", err)
	}

	return auth, nil
}

// Name of the test connector used to simulate identity provider initiated flow.
const idpInitiatedSAMLTestConn = "idp-initiated-saml-test-conn"

func (sas *SAMLAuthService) checkIDPInitiatedSAML(ctx context.Context, connector types.SAMLConnector, assertion *saml2.AssertionInfo) error {
	if !connector.GetAllowIDPInitiated() && connector.GetName() != idpInitiatedSAMLTestConn {
		return trace.AccessDenied("IdP initiated SAML is not allowed by the connector configuration")
	}

	// Record each assertion using its unique ID.
	for _, a := range assertion.Assertions {
		// Skip replay protection if either NotOnOrAfter is unset or invalid.
		// (not all IdPs provide this value, replay mitigation is best effort)
		if a.Conditions != nil && a.Conditions.NotOnOrAfter != "" {
			// Note: technically there are subtle differences between RFC3339 and XSD dateTime,
			// but the SAML libraries we use all parse RFC3339 so this should be sufficient.
			if validUntil, err := time.Parse(time.RFC3339, dateTimeToRFC3339(a.Conditions.NotOnOrAfter)); err == nil {
				if err := sas.assertionReplayService.RecognizeSSOAssertion(
					ctx,
					connector.GetName(),
					a.ID,
					assertion.NameID,
					validUntil,
				); err != nil {
					return trace.Wrap(err)
				}
			}
		}
	}

	return nil
}

// dateTimeToRFC3339 addresses a corner case with different timestamp formats.
// The XSD date time used by SAML allows 24:00:00 to represent the exact instant
// at the end of the day (equivalent to 00:00:00 of the following day), but
// this is not valid for RFC3339.
func dateTimeToRFC3339(dateTime string) string {
	return strings.Replace(dateTime, "T24:00:00", "T23:59:59", 1)
}

func (sas *SAMLAuthService) validateSAMLResponse(ctx context.Context, diagCtx *auth.SSODiagContext, samlResponse, connectorID, clientIP string) (*authclient.SAMLAuthResponse, string, error) {
	idpInitiated := false
	var connector types.SAMLConnector
	var provider *saml2.SAMLServiceProvider
	var request *types.SAMLAuthRequest
	requestID, err := ParseSAMLInResponseTo(samlResponse)

	if connectorID == idpInitiatedSAMLTestConn {
		// Simulate identity provider initiated SAML login, when there's no original request on our side.
		requestID = ""
		err = trace.NotFound("")
		diagCtx.Info.TestFlow = true
	}

	var mfaSession *services.SSOMFASessionData
	switch {
	case trace.IsNotFound(err):
		if connectorID == "" {
			return nil, "", trace.BadParameter("ACS URI did not include a valid SAML connector ID parameter")
		}

		idpInitiated = true
		connector, provider, err = sas.getSAMLConnectorAndProviderByID(ctx, connectorID, false /*forMFA*/)
		if err != nil {
			return nil, "", trace.Wrap(err, "Failed to get SAML connector and provider")
		}
	case err != nil:
		return nil, "", trace.Wrap(err)
	default:
		diagCtx.RequestID = requestID
		request, err = sas.auth.Services.GetSAMLAuthRequest(ctx, requestID)
		if err != nil {
			return nil, "", trace.Wrap(err, "Failed to get SAML Auth Request")
		}

		// Check if this is an MFA request.
		mfaSession, err = sas.auth.GetSSOMFASession(ctx, request.ID)
		if err != nil && !trace.IsNotFound(err) {
			return nil, "", trace.Wrap(err)
		}

		diagCtx.Info.TestFlow = request.SSOTestFlow
		connector, provider, err = sas.getSAMLConnectorAndProvider(ctx, *request, mfaSession != nil)
		if err != nil {
			return nil, "", trace.Wrap(err, "Failed to get SAML connector and provider")
		}
	}

	loginIP := ""
	userAgent := ""
	if request != nil {
		loginIP = request.ClientLoginIP
		userAgent = request.ClientUserAgent
	} else if clientIP != "" {
		// In case of IdP initiated login we don't have a request with the client IP, so we take the IP from
		// incoming connection, sent by the Proxy.
		loginIP = clientIP
	} else if addr, err := authz.ClientSrcAddrFromContext(ctx); err == nil {
		host, _, err := net.SplitHostPort(addr.String())
		if err != nil {
			return nil, "", trace.Wrap(err, "failed to parse client source address")
		}
		loginIP = host
	}

	assertionInfo, err := provider.RetrieveAssertionInfo(samlResponse)
	if err != nil {
		samlErr := trace.AccessDenied("received response with incorrect or missing attribute statements, please check the identity provider configuration to make sure that mappings for claims/attribute statements are set up correctly. <See: https://goteleport.com/docs/admin-guides/access-controls/sso/>, failed to retrieve SAML assertion info from response: %v.", err)
		return nil, loginIP, trace.WithUserMessage(samlErr, "Failed to retrieve assertion info. This may indicate IdP configuration error.")
	}

	if assertionInfo != nil {
		diagCtx.Info.SAMLAssertionInfo = (*types.AssertionInfo)(assertionInfo)
	}

	if idpInitiated {
		if err := sas.checkIDPInitiatedSAML(ctx, connector, assertionInfo); err != nil {
			if trace.IsAccessDenied(err) {
				logger.WarnContext(ctx, "Failed to process IdP-initiated login request, IdP-initiated login is disabled for this connector", "error", err)
			}

			return nil, loginIP, trace.Wrap(err)
		}
	}
	if assertionInfo.WarningInfo.InvalidTime {
		samlErr := trace.AccessDenied("invalid time in SAML assertion info")
		return nil, loginIP, trace.WithUserMessage(samlErr, "SAML assertion info contained warning: invalid time.")
	}

	if assertionInfo.WarningInfo.NotInAudience {
		samlErr := trace.AccessDenied("no audience in SAML assertion info")
		return nil, loginIP, trace.WithUserMessage(samlErr, "SAML: not in expected audience. Check auth connector audience field and IdP configuration for typos and other errors.")
	}

	logger.DebugContext(ctx, "Obtained SAML assertions", "assertion_info_name", assertionInfo.NameID, "warnings", assertionInfo.WarningInfo)

	// Maybe handle the case where a user authenticating on an Entra ID SAML connector has 150+ group assignments.
	if err := sas.maybeHandleEntraIDGroupsOverage(ctx, assertionInfo, connector); err != nil {
		logger.ErrorContext(ctx, "Failed to handle Entra ID groups overage", "connector", connector.GetName(), "error", err)
		return nil, loginIP, trace.Wrap(ErrSAMLEntraIDGroupsOverage)
	}

	diagCtx.Info.SAMLAttributeStatements = sas.getAttributeFromAssertion(assertionInfo)
	diagCtx.Info.SAMLAttributesToRoles = connector.GetAttributesToRoles()

	// Update the MFA session with a token. Return it to the user to complete the MFA check.
	if mfaSession != nil {
		// validate the mfaSession now that we have the full request details.
		if err := sas.validateMFASession(ctx, mfaSession, assertionInfo, connector.GetName()); err != nil {
			return nil, loginIP, trace.Wrap(err)
		}

		token, err := sas.auth.UpsertSSOMFASessionWithToken(ctx, mfaSession)
		if err != nil {
			return nil, loginIP, trace.Wrap(err)
		}

		return &authclient.SAMLAuthResponse{
			Req: SAMLAuthRequestFromProto(request),
			Identity: types.ExternalIdentity{
				ConnectorID: connector.GetName(),
				Username:    assertionInfo.NameID,
			},
			Username: assertionInfo.NameID,
			MFAToken: token,
		}, loginIP, nil
	}

	user, err := sas.auth.GetUser(ctx, assertionInfo.NameID, false)
	if err != nil && !trace.IsNotFound(err) {
		return nil, loginIP, trace.Wrap(err)
	}

	// We don't want to overwrite a sync-service based user with an
	// ephemeral one, so we do the user upsert *IF* and *ONLY IF* we
	// determine that:
	//
	//  - There is no user with that name in the system, or
	//  - The user with that name is an ephemeral, sso-connector
	//    created user.
	//
	// All Sync-service create users have an origin label, while those created
	// via calculateSAMLUser do not.
	var sessionTTL time.Duration
	if isEphemeralSAMLUser(user) {
		// This is an ephemeral SAML user: we can happily update and overwrite
		// this user.

		logger.DebugContext(ctx, "Applying SAML attribute to roles mappings", "attribute_to_roles_count", len(connector.GetAttributesToRoles()))

		// Calculate (figure out name, roles, traits, session TTL) of user and
		// create the user in the backend.
		params, err := sas.calculateSAMLUser(ctx, diagCtx, connector, *assertionInfo, request)
		if err != nil {
			return nil, loginIP, trace.Wrap(err, "Failed to calculate user attributes.")
		}

		diagCtx.Info.CreateUserParams = &types.CreateUserParams{
			ConnectorName: params.ConnectorName,
			Username:      params.Username,
			KubeGroups:    params.KubeGroups,
			KubeUsers:     params.KubeUsers,
			Roles:         params.Roles,
			Traits:        params.Traits,
			SessionTTL:    types.Duration(params.SessionTTL),
		}

		createSAMLUserParams := &CreateSAMLUserParams{
			CreateUserParams: auth.CreateUserParams{
				ConnectorName: params.ConnectorName,
				Username:      params.Username,
				KubeGroups:    params.KubeGroups,
				KubeUsers:     params.KubeUsers,
				Roles:         params.Roles,
				Traits:        params.Traits,
				SessionTTL:    params.SessionTTL,
			},
		}

		if connector.GetSingleLogoutURL() != "" {
			provider.IdentityProviderSLOURL = connector.GetSingleLogoutURL()
			createSAMLUserParams.SingleLogoutURL, err = generateSingleLogoutURL(
				provider,
				connector,
				assertionInfo,
			)
			if err != nil {
				return nil, loginIP, trace.Wrap(err, "Failed to generate SAML SLO URL")
			}
		}

		if len(params.Roles) == 0 {
			dryRun := true
			dryRunUser, err := sas.createSAMLUser(ctx, createSAMLUserParams, dryRun)
			if err != nil {
				return nil, loginIP, trace.Wrap(err)
			}

			uls, err := sas.auth.GeneratePureULS(ctx, dryRunUser)
			if err != nil {
				return nil, loginIP, trace.Wrap(err)
			}

			// If we know the user won't have any roles from Access List then bail early.
			// This is best-effort to avoid user being persisted and clears out any existing roles.
			// TODO(nixpig): Look into whether it's possible to refactor login hooks to work
			// on in-memory user object, rather than from backend. This would remove the need
			// to persist the user (and in doing so, the requirement to check if they would
			// have access list roles beforehand).
			if len(uls.GetAccessListRoles()) == 0 {
				return nil, loginIP, trace.Wrap(ErrSAMLNoRoles)
			}

			sessionRoles, err := services.FetchRoles(uls.GetRoles(), sas.auth, uls.GetTraits())
			if err != nil {
				return nil, loginIP, trace.Wrap(err)
			}
			createSAMLUserParams.SessionTTL = utils.MinTTL(sessionRoles.AdjustSessionTTL(apidefaults.MaxCertDuration), params.SessionTTL)
			diagCtx.Info.CreateUserParams.SessionTTL = types.Duration(createSAMLUserParams.SessionTTL)
		}

		user, err = sas.createSAMLUser(ctx, createSAMLUserParams, diagCtx.Info.TestFlow)
		if err != nil {
			return nil, loginIP, trace.Wrap(err, "Failed to create user from provided parameters.")
		}
		sessionTTL = createSAMLUserParams.SessionTTL
	}

	userState, err := sas.postProcessUser(ctx, user, connector, diagCtx, request, assertionInfo)
	if err != nil {
		return nil, loginIP, trace.Wrap(err)
	}

	if len(userState.GetRoles()) == 0 {
		return nil, loginIP, trace.Wrap(ErrSAMLNoRoles)
	}

	sessionRoles, err := services.FetchRoles(userState.GetRoles(), sas.auth, userState.GetTraits())
	if err != nil {
		return nil, loginIP, trace.Wrap(err)
	}
	sessionTTL = utils.MinTTL(sessionRoles.AdjustSessionTTL(apidefaults.MaxCertDuration), sessionTTL)

	// Auth was successful, return session, certificate, etc. to caller.
	resp := &authclient.SAMLAuthResponse{
		Identity: types.ExternalIdentity{
			ConnectorID: user.GetCreatedBy().Connector.ID,
			Username:    user.GetName(),
		},
		Username: userState.GetName(),
	}

	if request != nil {
		resp.Req = SAMLAuthRequestFromProto(request)
	} else {
		resp.Req = authclient.SAMLAuthRequest{
			CreateWebSession: true,
		}
	}

	var scope string
	if request != nil {
		scope = request.Scope
	}

	roles, err := services.FetchRoles(userState.GetRoles(), sas.auth, userState.GetTraits())
	if err != nil {
		return nil, loginIP, trace.Wrap(err)
	}

	// If the request is coming from a browser, create a web session.
	if request == nil || request.CreateWebSession {
		session, err := sas.auth.CreateWebSessionFromReq(ctx, auth.NewWebSessionRequest{
			User:                 userState.GetName(),
			Roles:                userState.GetRoles(),
			Traits:               userState.GetTraits(),
			SessionTTL:           utils.MinTTL(roles.AdjustSessionTTL(apidefaults.MaxCertDuration), sessionTTL),
			LoginTime:            sas.auth.GetClock().Now().UTC(),
			LoginIP:              loginIP,
			LoginUserAgent:       userAgent,
			AttestWebSession:     true,
			CreateDeviceWebToken: true,
			Scope:                scope,
		})
		if err != nil {
			return nil, loginIP, trace.Wrap(err, "Failed to create web session.")
		}

		resp.Session = session
	}

	// If a public key was provided, sign it and return a certificate.
	if request != nil && (len(request.SshPublicKey) > 0 || len(request.TlsPublicKey) > 0) {
		sshCert, tlsCert, err := sas.auth.CreateSessionCerts(ctx, &auth.SessionCertsRequest{
			UserState:               userState,
			SessionTTL:              utils.MinTTL(roles.AdjustSessionTTL(apidefaults.MaxCertDuration), sessionTTL),
			SSHPubKey:               request.SshPublicKey,
			TLSPubKey:               request.TlsPublicKey,
			Compatibility:           request.Compatibility,
			RouteToCluster:          request.RouteToCluster,
			KubernetesCluster:       request.KubernetesCluster,
			LoginIP:                 loginIP,
			SSHAttestationStatement: hardwarekey.AttestationStatementFromProto(request.SshAttestationStatement),
			TLSAttestationStatement: hardwarekey.AttestationStatementFromProto(request.TlsAttestationStatement),
			Scope:                   scope,
		})
		if err != nil {
			return nil, loginIP, trace.Wrap(err, "Failed to create session certificate.")
		}
		clusterName, err := sas.auth.GetClusterName(ctx)
		if err != nil {
			return nil, loginIP, trace.Wrap(err, "Failed to obtain cluster name.")
		}
		resp.Cert = sshCert
		resp.TLSCert = tlsCert

		// Return the host CA for this cluster only.
		authority, err := sas.auth.GetCertAuthority(ctx, types.CertAuthID{
			Type:       types.HostCA,
			DomainName: clusterName.GetClusterName(),
		}, false)
		if err != nil {
			return nil, loginIP, trace.Wrap(err, "Failed to obtain cluster's host CA.")
		}
		resp.HostSigners = append(resp.HostSigners, authority)
	}

	if o, err := sas.auth.ClientOptionsForLogin(userState); err == nil {
		resp.ClientOptions = o
	} else {
		logger.WarnContext(ctx, "Failed to calculate client options for SAML login", "username", user.GetName(), "error", err)
	}

	diagCtx.Info.Success = true
	return resp, loginIP, nil
}

// validateMFASession checks the MFA session has the required request details.
func (sas *SAMLAuthService) validateMFASession(ctx context.Context, mfaSession *services.SSOMFASessionData, assertionInfo *saml2.AssertionInfo, connectorName string) error {
	switch {
	case mfaSession.ConnectorID != connectorName:
		return trace.AccessDenied("invalid SAML MFA session, wrong provider %q", mfaSession.ConnectorID)
	case mfaSession.ConnectorType != constants.SAML:
		return trace.AccessDenied("invalid SAML MFA session, wrong sso type %q", mfaSession.ConnectorType)
	case mfaSession.Username != assertionInfo.NameID:
		logger.WarnContext(ctx, "User attempted to validate an SSO MFA session belonging to a different user, denied", "user", assertionInfo.NameID)
		return trace.AccessDenied("invalid SAML MFA session")
	}

	return nil
}

// maybeHandleEntraIDGroupsOverage checks for the presence of "groups.link" attribute on the
// assertion, if it's present then attempts to fetch the groups overage and add back to the
// "groups" attribute of the assertion.
func (sas *SAMLAuthService) maybeHandleEntraIDGroupsOverage(
	ctx context.Context,
	assertionInfo *saml2.AssertionInfo,
	connector types.SAMLConnector,
) error {
	if !entraid.HasSAMLGroupsOverage(assertionInfo) {
		return nil
	}

	if connector.IsEntraIDGroupsProviderDisabled() {
		logger.DebugContext(ctx, "Entra ID groups provider is disabled")
		return nil
	}

	resolver, err := sas.entraIDTokenResolver()
	if err != nil {
		return trace.Wrap(err, "Failed to initialize Entra ID token resolver")
	}

	groupsProvider, err := entraid.NewSAMLEntraIDGroupsProvider(entraid.SAMLEntraIDGroupsProviderConfig{
		Connector:      connector,
		AssertionInfo:  assertionInfo,
		Logger:         logger,
		ResolveToken:   resolver.ResolveToken,
		NewGraphClient: sas.newEntraIDGraphClient,
	})
	if err != nil {
		return trace.Wrap(err, "Failed to create Entra ID groups provider")
	}

	if err := groupsProvider.MaybeFetchEntraIDGroups(ctx); err != nil {
		return trace.Wrap(err, "Failed to fetch Entra ID groups overage")
	}

	return nil
}

func isEphemeralSAMLUser(user types.User) bool {
	return user == nil || user.Origin() == ""
}

func (sas *SAMLAuthService) getAttributeFromAssertion(assertionInfo *saml2.AssertionInfo) map[string][]string {
	attributeStatements := map[string][]string{}
	for key, val := range assertionInfo.Values {
		var vals []string
		for _, vv := range val.Values {
			vals = append(vals, vv.Value)
		}
		logger.DebugContext(context.Background(), "Found SAML assertion", "key", key, "values", vals)
		attributeStatements[key] = vals
	}
	return attributeStatements
}

func (sas *SAMLAuthService) postProcessUser(ctx context.Context, user types.User, connector types.SAMLConnector, diagCtx *auth.SSODiagContext, request *types.SAMLAuthRequest, info *saml2.AssertionInfo) (services.UserState, error) {
	if !isEphemeralSAMLUser(user) {
		params, err := sas.calculateSAMLUser(ctx, diagCtx, connector, *info, request)
		if err != nil {
			return nil, trace.Wrap(err, "Failed to calculate user attributes.")
		}

		// ensure that any roles marked for preservation are preserved in the
		// calculated role set. This is to ensure we don't blow away any roles
		// required for integrations to work.
		preservedRoles, _ := sas.preservedRoles.Load(user.Origin())
		for _, originalRole := range user.GetRoles() {
			if slices.Contains(preservedRoles, originalRole) {
				params.Roles = append(params.Roles, originalRole)
			}
		}

		// ensure that the calculated roleset elements are unique
		params.Roles = apiutils.Deduplicate(params.Roles)
		user.SetRoles(params.Roles)

		// Long-lived (non-ephemeral) SAML users are not user-editable, so they
		// should not have any traits outside those created by either:
		//  - their integration of origin (e.g. Okta user sync),
		//  - the SAML connector from the SAML assertions, or
		//  - the application of any Login Rules
		//
		// To ensure that there are no spurious traits being preserved inside the
		// user we filter out all non-integration-supplied traits before merging
		// in the SAML- and LoginRule-derived traits.
		traits := filterUserTraits(user, &defaultSAMLTraitAllowList)

		// Now we can merge the traits generated by the SAML Connector and
		// the applied Login Rules in `params.Traits` into the preserved traits
		// from the original user without fear of clobbering anything important
		maps.Copy(traits, params.Traits)
		user.SetTraits(traits)

		if len(params.Roles) == 0 {
			// If we know the user won't have any roles from Access List then bail early.
			// This is best-effort to avoid user being persisted and clears out any existing roles.
			// TODO(nixpig): Look into whether it's possible to refactor login hooks to work
			// on in-memory user object, rather than from backend. This would remove the need
			// to persist the user (and in doing so, the requirement to check if they would
			// have access list roles beforehand).
			if err := sas.checkAccessListRoles(ctx, user); err != nil {
				logger.WarnContext(ctx, "Failed access list roles check", "error", err)
				return nil, trace.Wrap(err)
			}
		}

		if _, err := sas.auth.UpdateUser(ctx, user); err != nil {
			return nil, trace.Wrap(err)
		}
	}
	// CallLoginHooks needs to be called on updated user object.
	if err := sas.auth.CallLoginHooks(ctx, user); err != nil {
		return nil, trace.Wrap(err)
	}
	userState, err := sas.auth.GetUserOrLoginState(ctx, user.GetName())
	if err != nil {
		return nil, trace.Wrap(err)
	}

	// This is the final role set after evaluating connector-mapped and Teleport-assigned roles.
	if len(userState.GetRoles()) == 0 {
		return nil, trace.Wrap(ErrSAMLNoRoles)
	}

	return userState, nil
}

// checkAccessListRoles returns nil if the user will have access list roles.
// It is called from the ephemeral and non-ephemeral user login flows to determine
// whether to proceed when the user has no connector-mapped roles.
func (sas *SAMLAuthService) checkAccessListRoles(ctx context.Context, user types.User) error {
	willHaveAccessListRoles, err := willHaveAccessListRoles(ctx, sas.auth, user)
	if err != nil {
		return trace.Wrap(err)
	}
	if !willHaveAccessListRoles {
		return trace.Wrap(ErrSAMLNoRoles)
	}
	return nil
}

// traitAllowList defies a set of trait name matchers
type traitAllowList struct {
	byPrefix     []string
	byExactMatch []string
}

func (al *traitAllowList) allows(key string) bool {
	for _, prefix := range al.byPrefix {
		if strings.HasPrefix(key, prefix) {
			return true
		}
	}
	for _, value := range al.byExactMatch {
		if key == value {
			return true
		}
	}
	return false
}

// defaultSAMLTraitAllowList holds the default list of trait name matchers that
// indicate which user traits are to be preserved during a SAML login. Traits
// matched by any of these predicates are assumed to come from an integration
// service and are preserved during a SAML login, while everything else is
// filtered out.
var defaultSAMLTraitAllowList traitAllowList = traitAllowList{
	byPrefix: []string{
		"okta/",
		"scim/",
	},
	byExactMatch: []string{
		"http://schemas.microsoft.com/identity/claims/displayname",
		"http://schemas.microsoft.com/identity/claims/objectidentifier",
		"http://schemas.microsoft.com/identity/claims/tenantid",
		"http://schemas.microsoft.com/ws/2008/06/identity/claims/groups",
		"http://schemas.microsoft.com/ws/2008/06/identity/claims/roles",
		"http://schemas.xmlsoap.org/ws/2005/05/identity/claims/emailaddress",
		"http://schemas.xmlsoap.org/ws/2005/05/identity/claims/givenname",
		"http://schemas.xmlsoap.org/ws/2005/05/identity/claims/name",
		"http://schemas.xmlsoap.org/ws/2005/05/identity/claims/surname",
	},
}

func filterUserTraits(user types.User, allowList *traitAllowList) map[string][]string {
	existingTraits := user.GetTraits()
	filteredTraits := make(map[string][]string, len(existingTraits))

	for key, values := range existingTraits {
		if allowList.allows(key) {
			filteredTraits[key] = values
		}
	}

	return filteredTraits
}

// validateSAMLResponseWeb provides a HTTP/JSON interface to
// SAMLAuthService.ValidateSAMLResponse. It is called by a teleport proxy in
// response to it receiving the SAML callback (ACS) from the identity provider.
//
// TODO(strideynet): DELETE IN v20.0.0 - this has been migrated to gRPC from v19.
func validateSAMLResponseWeb(authClient *auth.ServerWithRoles, w http.ResponseWriter, r *http.Request, p httprouter.Params, version string) (any, error) {
	var req *authclient.ValidateSAMLResponseReq
	if err := httplib.ReadJSON(r, &req); err != nil {
		return nil, trace.Wrap(err)
	}
	response, err := authClient.ValidateSAMLResponse(r.Context(), req.Response, req.ConnectorID, req.ClientIP)
	if err != nil {
		return nil, trace.Wrap(err)
	}
	raw := authclient.SAMLAuthRawResponse{
		Username:      response.Username,
		Identity:      response.Identity,
		Cert:          response.Cert,
		Req:           response.Req,
		TLSCert:       response.TLSCert,
		MFAToken:      response.MFAToken,
		ClientOptions: response.ClientOptions,
	}
	if response.Session != nil {
		rawSession, err := services.MarshalWebSession(response.Session, services.WithVersion(version))
		if err != nil {
			return nil, trace.Wrap(err)
		}
		raw.Session = rawSession
	}
	raw.HostSigners = make([]json.RawMessage, len(response.HostSigners))
	for i, ca := range response.HostSigners {
		data, err := services.MarshalCertAuthority(ca, services.WithVersion(version))
		if err != nil {
			return nil, trace.Wrap(err)
		}
		raw.HostSigners[i] = data
	}
	return &raw, nil
}

// generateSingleLogoutURL generates a URL with a SAML LogoutRequest encoded in the query parameters. When the user opens this URL in the browser, it will initate
// SAML SLO (Single log-out) and log them out of the identity provider.
func generateSingleLogoutURL(provider *saml2.SAMLServiceProvider, connector types.SAMLConnector, assertionInfo *saml2.AssertionInfo) (string, error) {
	logoutRequest, err := provider.BuildLogoutRequestDocument(assertionInfo.NameID, assertionInfo.SessionIndex)
	if err != nil {
		return "", trace.Wrap(err, "Failed to build logout request.")
	}
	logoutRequest.Root().CreateAttr("Destination", connector.GetSingleLogoutURL())

	URL, err := provider.BuildLogoutURLRedirect(fmt.Sprintf("%s,%s", assertionInfo.NameID, connector.GetDisplay()), logoutRequest)
	if err != nil {
		return "", trace.Wrap(err, "Failed to build single-logout URL.")
	}

	return URL, nil
}
