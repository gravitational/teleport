// SAMLAuthService implements the logic of the SAML connector, allowing SSO
// logins using the SAML protocol.
//
// SAMLAuthService implements the SAMLService interface.
type SAMLAuthService struct {
	auth                   *auth.Server
	emitter                apievents.Emitter
	assertionReplayService *local.AssertionReplayService
	samlProviders          map[samlProviderKey]*samlProvider
	lock                   sync.Mutex
	licenseChecker         LicenseChecker

	// preservedRoles holds a list of roles that must be preserved during SAML
	// role calculation, based on the user's Origin. These are only applied to
	// long-lived users; ephemeral users should have no roles outside those
	// generated by the attribute-to-role mapping.
	preservedRoles utils.SyncMap[string, []string]
	// entraIDTokenResolver lazily initializes and returns the Entra ID token resolver
	// when handling Entra groups overage.
	entraIDTokenResolver func() (*entraid.TokenResolver, error)
	// newEntraIDGraphClient constructs an MS Graph client.
	// If it's not set, the Entra ID groups provider constructs its own default client.
	newEntraIDGraphClient func(tokenProvider azcore.TokenCredential, graphEndpoint string) (*msgraph.Client, error)
}

type SAMLAuthServiceConfig struct {
	Auth                   *auth.Server
	Emitter                apievents.Emitter
	AssertionReplayService *local.AssertionReplayService
	PreservedRoles         map[string][]string
	LicenseChecker         LicenseChecker
}

const maxCompressedBytes = 1024 * 1024 // 1 MB, will error if size is hit

func (cfg *SAMLAuthServiceConfig) CheckAndSetDefaults() error {
	if cfg.Auth == nil {
		return trace.BadParameter("auth.Server not provided")
	}
	if cfg.AssertionReplayService == nil {
		cfg.AssertionReplayService = cfg.Auth.Unstable.AssertionReplayService
	}
	if cfg.Emitter == nil {
		cfg.Emitter = events.NewDiscardEmitter()
	}
	if cfg.PreservedRoles == nil {
		cfg.PreservedRoles = map[string][]string{
			types.OriginOkta: {teleport.SystemOktaRequesterRoleName},
		}
	}
	if cfg.LicenseChecker == nil {
		return trace.BadParameter("license checker not provided")
	}
	return nil
}

// NewSAMLAuthService returns a SAMLAuthService configured to use the
// services given in the config.
func NewSAMLAuthService(cfg *SAMLAuthServiceConfig) (*SAMLAuthService, error) {
	if err := cfg.CheckAndSetDefaults(); err != nil {
		return nil, err
	}

	svc := &SAMLAuthService{
		auth:                   cfg.Auth,
		emitter:                cfg.Emitter,
		assertionReplayService: cfg.AssertionReplayService,
		samlProviders:          make(map[samlProviderKey]*samlProvider),
		licenseChecker:         cfg.LicenseChecker,
		entraIDTokenResolver: sync.OnceValues(func() (*entraid.TokenResolver, error) {
			return entraid.NewTokenResolver(entraid.TokenResolverConfig{
				Plugins:      cfg.Auth.Plugins,
				Integrations: cfg.Auth.Integrations,
				Logger:       logger,
				TokenGenerator: func(ctx context.Context) (string, error) {
					return azureoidc.GenerateEntraOIDCToken(ctx, cfg.Auth.Cache, cfg.Auth.GetKeyStore(), cfg.Auth.GetClock())
				},
			})
		}),
	}
	svc.preservedRoles.Set(cfg.PreservedRoles)

	return svc, nil
}

// samlProvider is internal structure that stores SAML client and its config
type samlProvider struct {
	provider  *saml2.SAMLServiceProvider
	connector types.SAMLConnector
}

// samlProviderKey is an internal key for a samlProvider.
type samlProviderKey struct {
	name string
	// The saml client settings for an MFA saml connector differ from the
	// base saml connector, so we need to differentiate between them.
	forMFA bool
}

