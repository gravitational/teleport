package legacy

import (
	"context"

	"github.com/hashicorp/terraform-plugin-framework/path"
	"github.com/hashicorp/terraform-plugin-framework/resource"
)

// ModifyPlan modifies the OIDC connector plan.
// It sets `spec.claims_to_roles` to empty when omitted so existing mappings are cleared instead of preserved.
func (r resourceTeleportOIDCConnector) ModifyPlan(ctx context.Context, req resource.ModifyPlanRequest, resp *resource.ModifyPlanResponse) {
	if req.Plan.Raw.IsNull() || req.State.Raw.IsNull() {
		return
	}

	planEmptyListWhenOmitted(ctx, req, resp, path.Root("spec").AtName("claims_to_roles"))
}
