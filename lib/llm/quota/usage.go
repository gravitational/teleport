package quota

import (
	"math/bits"

	"github.com/gravitational/trace"
)

// Usage is an amount of LLM tokens. It is used both to describe reservations
// and the effective consumption reported by providers.
type Usage struct {
	// InputTokens is the number of tokens sent to the provider.
	InputTokens uint
	// OutputTokens is the number of tokens generated by the provider.
	OutputTokens uint
}

// Add increases the usage by the provided amount.
//
// It returns an error if either sum overflows, in which case the usage is left
// unchanged, so callers can safely keep using it.
func (u *Usage) Add(a Usage) error {
	input, carry := bits.Add(u.InputTokens, a.InputTokens, 0)
	if carry != 0 {
		return trace.BadParameter("input tokens exceeded")
	}

	output, carry := bits.Add(u.OutputTokens, a.OutputTokens, 0)
	if carry != 0 {
		return trace.BadParameter("output tokens exceeded")
	}

	u.InputTokens = input
	u.OutputTokens = output

	return nil
}

// Sub decreases the usage by the provided amount.
//
// Since token counts are unsigned, it returns an error if either subtraction
// would go negative, in which case the usage is left unchanged, so callers can
// safely keep using it.
func (u *Usage) Sub(a Usage) error {
	input, borrow := bits.Sub(u.InputTokens, a.InputTokens, 0)
	if borrow != 0 {
		return trace.BadParameter("negative input token count")
	}

	output, borrow := bits.Sub(u.OutputTokens, a.OutputTokens, 0)
	if borrow != 0 {
		return trace.BadParameter("negative output token count")
	}

	u.InputTokens = input
	u.OutputTokens = output

	return nil
}
